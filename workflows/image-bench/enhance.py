def wait_for_queue(limit_s: int = 3600) -> bool:
    start = time.time()
    while time.time() - start < limit_s:
        try:
            q = json.load(urllib.request.urlopen(SRV + "/queue", timeout=15))
        except Exception:
            time.sleep(5)
            continue
        if not (q.get("queue_running") or q.get("queue_pending")):
            return True
        time.sleep(5)
    return False


def submit(graph: dict, dest: Path, timeout_s: int = 1800) -> float | None:
    if not wait_for_queue():
        print("    queue never freed")
        return None
    started = time.time()
    try:
        req = urllib.request.Request(
            SRV + "/prompt", data=json.dumps({"prompt": graph, "client_id": "enhance"}).encode(),
            headers={"Content-Type": "application/json"})
        pid = json.load(urllib.request.urlopen(req, timeout=60))["prompt_id"]
    except urllib.error.HTTPError as exc:
        print(f"    FAIL submit: {exc.read().decode()[:400]}")
        return None
    while True:
        if time.time() - started > timeout_s:
            print("    TIMEOUT")
            return None
        time.sleep(3)
        try:
            hist = json.load(urllib.request.urlopen(f"{SRV}/history/{pid}", timeout=120))
        except Exception:
            print("    LOST: backend died")
            return None
        if pid in hist:
            break
    entry = hist[pid]
    if not entry.get("status", {}).get("completed", True):
        print(f"    FAIL: {json.dumps(entry.get('status', {}).get('messages', []))[-400:]}")
        return None
    for _nid, out in entry.get("outputs", {}).items():
        for image in out.get("images", []):
            qs = urllib.parse.urlencode({"filename": image["filename"],
                                         "subfolder": image.get("subfolder", ""),
                                         "type": image.get("type", "output")})
            dest.write_bytes(urllib.request.urlopen(f"{SRV}/view?{qs}", timeout=300).read())
    return round(time.time() - started, 1)


def stage(name: str, graph: dict, dest: Path) -> None:
    secs = submit(graph, dest)
    print(f"  {name:38} {'FAILED' if secs is None else f'{secs:7.1f}s -> {dest.name}'}")


