def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="projects/image-bench/enhanced")
    ap.add_argument("--base", default="projects/image-bench/zImageTurbo.png")
    ap.add_argument("--face", default="projects/burningman/anchor/anchor_face.png")
    ap.add_argument("--seed", type=int, default=4242)
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    base, face = Path(args.base), Path(args.face)

    # ComfyUI's LoadImage only sees its own input directory
    staged_base = staged_face = None
    if base.is_file():
        staged_base = "bench_base.png"
        shutil.copy2(base, COMFY_INPUT / staged_base)
    if face.is_file():
        staged_face = "bench_face.png"
        shutil.copy2(face, COMFY_INPUT / staged_face)
    print(f"base: {base if staged_base else 'MISSING'}\nface: {face if staged_face else 'MISSING'}\n")

    print("ENHANCE - improving a finished render")
    if staged_base:
        stage("4x-UltraSharp upscale", g_upscale(staged_base), out / "enh_upscale.png")
    stage("hires fix (latent 1.5x, denoise 0.4)", g_hires(args.seed), out / "enh_hires.png")

    print("\nCONDITION - changing what gets generated")
    for strength in (0.0, 0.6, 1.2):
        stage(f"LoRA Z-Detail-Slider @ {strength}", g_lora(args.seed, strength),
              out / f"cond_lora_{strength}.png")
    if staged_base:
        for denoise in (0.35, 0.60, 0.85):
            stage(f"img2img denoise {denoise}", g_img2img(staged_base, denoise, args.seed),
                  out / f"cond_img2img_{denoise}.png")
    if staged_face:
        stage("Klein reference latent (identity in)", g_klein_reference(staged_face, args.seed),
              out / "cond_klein_reference.png")
        if staged_base:
            stage("ReActor face swap (identity after)", g_faceswap(staged_base, staged_face),
                  out / "cond_faceswap.png")
    print(f"\n-> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
