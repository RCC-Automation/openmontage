"""Everything you can do to an image here beyond typing a prompt.

Two families of technique, and the difference matters:

  ENHANCE  - takes a finished render and improves it. Upscale, hires-fix,
             face-restore. No new creative input.
  CONDITION - changes what gets generated by feeding something in besides text:
             an image (img2img), a reference identity (Klein ReferenceLatent,
             IP-Adapter FaceID), or a face pasted afterwards (ReActor).

    python workflows/image-bench/enhance.py --base projects/image-bench/zImageTurbo.png

Run after run_bench.py. Waits for a free queue before every submission.
"""

